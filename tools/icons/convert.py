#!/usr/bin/env python3
"""Convert the Material Symbols Rounded SVGs in material-symbols-rounded/ into Android vector drawables.

Only icons the app actually uses live in that folder (downloaded once from the npm package
@material-symbols/svg-500, Apache-2.0). Nothing is loaded at runtime.

Usage: python3 tools/icons/convert.py   (writes app/src/main/res/drawable/ic_<name>.xml)
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
SRC = ROOT / "tools/icons/material-symbols-rounded"
OUT = ROOT / "app/src/main/res/drawable"

TEMPLATE = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/icons/convert.py from Material Symbols Rounded "{name}" (Apache-2.0). Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960"
    android:tint="?android:attr/textColorPrimary">
    <group android:translateY="960">
        <path
            android:fillColor="@android:color/white"
            android:pathData="{path}" />
    </group>
</vector>
"""


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for svg in sorted(SRC.glob("*.svg")):
        text = svg.read_text()
        assert 'viewBox="0 -960 960 960"' in text, svg.name
        paths = re.findall(r'<path d="([^"]+)"', text)
        assert len(paths) == 1, svg.name
        name = svg.stem.replace("-", "_")
        (OUT / f"ic_{name}.xml").write_text(TEMPLATE.format(name=svg.stem, path=paths[0]))
        print("ic_" + name)


if __name__ == "__main__":
    main()
